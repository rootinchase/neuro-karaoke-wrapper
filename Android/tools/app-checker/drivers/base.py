"""The surface-agnostic driver interface the crawler talks to."""
from typing import Protocol


class Driver(Protocol):
    def to_root(self) -> None: ...
    def dump(self) -> list: ...            # -> list[Node]
    def screenshot(self, path: str) -> None: ...
    def read_logcat(self) -> str: ...
    def enter(self, node) -> None: ...
    def back(self) -> None: ...
